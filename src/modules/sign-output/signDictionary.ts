/**
 * Returns all sign entries in the dictionary.
 */
export function getAllSignEntries(): SignEntry[] {
  return Object.values(SIGN_DICTIONARY);
}

/**
 * Looks up a sign entry by its token.
 */
export function getSignEntry(token: string): SignEntry | null {
  if (!token) return null;
  const normalized = token.toUpperCase().trim();
  return SIGN_DICTIONARY[normalized] || null;
}
